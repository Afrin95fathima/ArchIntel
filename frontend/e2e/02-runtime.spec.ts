import {test,expect} from '@playwright/test';
import {signIn} from './security-helper';

test('runtime plan, strict telemetry, quality, graphs and frozen export',async({page})=>{
  await signIn(page);const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.getByRole('button',{name:'Explore demo application'}).click();
  await expect(page.getByRole('heading',{name:'A clearer picture. A smarter next step.'})).toBeVisible({timeout:150000});
  await page.getByRole('button',{name:'Dynamic analysis',exact:true}).click();
  await page.getByLabel('Session name',{exact:true}).fill('Browser phase 3');
  await page.getByRole('button',{name:'Preview instrumentation plan',exact:true}).click();
  await expect(page.getByText(/Instrumentation plan: \d+ classes/).first()).toBeVisible();
  const creation=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/runtime-sessions'));
  await page.getByRole('button',{name:'Create runtime session',exact:true}).click();
  const created=await (await creation).json();expect(created.agent.binding_mode).toBe('STRICT');
  await expect(page.getByRole('heading',{name:'Connect your Java application'})).toBeVisible();
  await page.getByRole('button',{name:'Hide connection settings'}).click();
  const row=page.getByRole('row').filter({hasText:'Browser phase 3'});
  await row.getByRole('button',{name:'Start',exact:true}).click();
  await expect(row.getByRole('cell',{name:'WAITING_FOR_AGENT',exact:true})).toBeVisible();
  const url='/api/v1/runtime-sessions/'+created.session.id;
  const baseline=await (await page.request.get('/api/v1/analyses/'+created.session.analysis_id+'/export')).json();
  const cls=baseline.classes.find((c:{methods?:{name:string}[]})=>c.methods?.some(m=>m.name==='work'))||baseline.classes[0];
  const method=cls.methods?.find((m:{name:string})=>m.name&&!m.name.startsWith('<'))?.name||'work';
  const attributes=(values:Record<string,string>)=>Object.entries(values).map(([key,value])=>({key,value:{stringValue:value}}));
  const spans=[{traceId:'1'.repeat(32),spanId:'1'.repeat(16),startTimeUnixNano:'1000000000',endTimeUnixNano:'1001000000',attributes:attributes({'code.namespace':cls.id,'code.function':method})}];
  const missing={resourceSpans:[{scopeSpans:[{spans}]}]};
  const headers={Authorization:'Bearer '+created.token};
  expect((await page.request.post(url+'/v1/traces',{headers,data:missing})).status()).toBe(409);
  const data={resourceSpans:[{resource:{attributes:attributes({'service.name':created.agent.environment.OTEL_SERVICE_NAME,'archintel.artifact.sha256':created.agent.environment.OTEL_RESOURCE_ATTRIBUTES.split('=')[1]})},scopeSpans:[{spans}]}]};
  for(let i=0;i<2;i++)expect((await page.request.post(url+'/v1/traces',{headers,data})).ok()).toBeTruthy();
  await expect(row.getByRole('cell',{name:'RUNNING',exact:true})).toBeVisible({timeout:15000});
  await expect(page.getByText('1 accepted spans · 1 duplicates · 0 conflicts · 0 dropped')).toBeVisible({timeout:20000});
  await expect(page.getByText('binding rejected spans: 1',{exact:true})).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/phase3-runtime-quality.png',fullPage:true});
  await page.getByRole('button',{name:'Graph',exact:true}).click();
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.getByLabel('Runtime graph level').selectOption('classes');
  await page.getByLabel('Runtime graph mode').selectOption('runtime');
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await row.getByRole('button',{name:'Stop',exact:true}).click();
  await expect(row.getByRole('cell',{name:'COMPLETED',exact:true})).toBeVisible();
  const frozen=await (await page.request.get(url+'/evidence')).json();
  expect((await page.request.post(url+'/v1/traces',{headers,data})).status()).toBe(409);
  await page.reload();await page.getByRole('button',{name:'Dynamic analysis',exact:true}).click();
  await page.getByLabel('Select Browser phase 3',{exact:true}).check();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export evidence',exact:true}).click();
  expect((await download).suggestedFilename()).toBe('archintel-runtime-report.json');
  expect(await (await page.request.get(url+'/evidence')).json()).toEqual(frozen);
  expect(await (await page.request.get('/api/v1/analyses/'+created.session.analysis_id+'/export')).json()).toEqual(baseline);
  expect(errors).toEqual([]);
});
