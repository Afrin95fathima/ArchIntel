import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {owner} from './security-helper';

test('first setup, password change, restricted identity and workspace isolation in the browser',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Set up your administrator'})).toBeVisible();
  await page.getByLabel('Setup key').fill(readFileSync(path.join(process.env.ARCHINTEL_BROWSER_DATA!,'security-bootstrap.key'),'utf8').trim());
  await page.getByLabel('Username',{exact:true}).fill(owner.username);
  await page.getByLabel('Password',{exact:true}).fill(owner.password);
  await page.getByRole('button',{name:'Create administrator'}).click();
  await expect(page.getByText('Services ready')).toBeVisible();
  await page.getByRole('button',{name:'Security & access',exact:true}).click();
  await page.getByLabel('Current password',{exact:true}).fill(owner.password);
  await page.getByLabel('New password',{exact:true}).fill(owner.password);
  const passwordChange=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/security/password'));
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  expect((await passwordChange).status()).toBe(200);
  await expect(page.getByRole('status')).toContainText('Password changed');
  await page.getByLabel('New username').fill('browser-reader');
  await page.getByLabel('Initial password').fill('browser-reader-password');
  await page.getByRole('button',{name:'Create identity'}).click();
  await expect(page.getByRole('status')).toContainText('Identity created');
  await page.getByLabel('Workspace name',{exact:true}).fill('Separate tenant');
  await page.getByLabel('Administrator username').fill('browser-other');
  await page.getByLabel('Administrator password').fill('browser-other-password');
  await page.getByRole('button',{name:'Create workspace',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Workspace created');
  await page.getByRole('button',{name:'Verify audit chain'}).click();
  await expect(page.getByRole('status')).toContainText('Audit chain valid');
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Sign in to ArchIntel'})).toBeVisible();
  await page.getByLabel('Username',{exact:true}).fill('browser-reader');
  await page.getByLabel('Password',{exact:true}).fill('browser-reader-password');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Security & access',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Change your password'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'People and service identities'})).toHaveCount(0);
  expect((await page.request.get('/api/v1/security/principals')).status()).toBe(403);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Sign in to ArchIntel'})).toBeVisible();
  expect((await page.request.get('/api/v1/projects')).status()).toBe(401);
  expect(errors).toEqual([]);
});
