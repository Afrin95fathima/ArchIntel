import { test, expect } from '@playwright/test';
import path from 'node:path';
import {signIn} from './security-helper';
test.beforeEach(async({page})=>{await signIn(page);});

test('investor walkthrough uses live persisted analysis across every screen',async({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('Services ready')).toBeVisible();
  await page.getByRole('button',{name:'Explore demo application'}).click();
  await expect(page.getByRole('heading',{name:'A clearer picture. A smarter next step.'})).toBeVisible({timeout:150000});
  await page.screenshot({path:'../docs/screenshots/overview.png',fullPage:true});
  await page.getByRole('button',{name:'Architecture explorer',exact:true}).click();
  await expect(page.locator('.graph-canvas canvas').first()).toBeVisible();
  await page.getByRole('button',{name:'Packages',exact:true}).click();
  await expect(page.locator('.graph-footer')).toContainText('nodes');
  await page.getByRole('button',{name:'Classes',exact:true}).click();
  await expect(page.locator('.graph-footer')).toContainText('nodes');
  await page.screenshot({path:'../docs/screenshots/explorer.png',fullPage:true});
  await page.getByRole('button',{name:'Candidate domains',exact:true}).click();
  await page.getByRole('row').filter({hasText:'Payment'}).click();
  await expect(page.getByRole('dialog',{name:'Domain detail'})).toContainText('Why this boundary?');
  await page.getByLabel('Close domain').click();
  await page.getByRole('button',{name:/Technical debt/}).click();
  await page.getByLabel('Severity',{exact:true}).selectOption('CRITICAL');
  await expect(page.locator('.issue-row').first()).toBeVisible();
  await page.locator('.issue-row').first().click();
  await expect(page.getByText('Recommended investigation',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Dependencies',exact:true}).click();
  await expect(page.locator('.cycle-card').first()).toBeVisible();
  await page.getByRole('tab',{name:'Architecture metrics'}).click();
  await expect(page.getByRole('img',{name:'Package abstractness versus instability scatter plot'})).toBeVisible();
  await page.getByRole('button',{name:'Modernization',exact:true}).click();
  await page.getByRole('tab',{name:'Extraction sequence'}).click();
  await page.locator('tbody tr').first().click();
  await expect(page.getByText('Risks and blockers')).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/modernization.png',fullPage:true});
  await page.getByRole('button',{name:'Open architecture assistant'}).click();
  await page.getByLabel('Ask an architecture question').fill('Why is Payment high risk?');
  await page.getByLabel('Send question').click();
  await expect(page.getByText(/FROM THE ANALYSIS · NO MODEL|AI-GENERATED · CITED/).first()).toBeVisible();
  await expect(page.locator('.fact').first()).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/assistant.png',fullPage:true});
  const exportUrl=await page.getByRole('link',{name:'Export analysis'}).getAttribute('href');
  const exported=await page.request.get(exportUrl!);
  expect(exported.ok()).toBeTruthy();
  expect((await exported.json()).summary.class_count).toBe(40);
  await page.getByRole('button',{name:'Reports',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Reports',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Design system',exact:true}).click();
  await expect(page.getByRole('heading',{name:'ArchIntel interface catalog'})).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/ui-kit.png',fullPage:true});
  expect(errors).toEqual([]);
});

test('real artifact upload reaches completed results',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Analyze application',exact:true}).click();
  await page.getByLabel('New project name').fill('Browser verification');
  await page.getByLabel('Application name',{exact:true}).fill('WAR verification');
  await page.getByLabel('Java artifact').setInputFiles(path.resolve('../samples/northstar-commerce.war'));
  await page.getByRole('button',{name:'Start architecture analysis'}).click();
  await expect(page.getByRole('heading',{name:'A clearer picture. A smarter next step.'})).toBeVisible({timeout:150000});
  await expect(page.getByText('northstar-commerce.war',{exact:true})).toBeVisible();
});
