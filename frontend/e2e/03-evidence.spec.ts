import {test,expect} from '@playwright/test';
import {signIn} from './security-helper';

test('architecture version preview, canonical provenance, discovery and persistent twin',async({page})=>{
  test.skip(process.env.ARCHINTEL_RUN_GRAPH_TESTS!=='1','Requires the prepared local Neo4j projection service.');
  await signIn(page);const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.getByRole('button',{name:'Explore demo application'}).click();
  await expect(page.getByRole('heading',{name:'A clearer picture. A smarter next step.'})).toBeVisible({timeout:150000});
  await page.getByRole('button',{name:'Evidence & digital twin',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Trace conclusions to their evidence.'})).toBeVisible();
  await page.getByLabel('Version name',{exact:true}).fill('Browser evidence version');
  await page.getByRole('button',{name:'Preview architecture version',exact:true}).click();
  await expect(page.getByText(/Preview: \d+ facts/)).toBeVisible();
  const creation=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/architecture-versions'));
  await page.getByRole('button',{name:'Save architecture version',exact:true}).click();
  const created=await (await creation).json();expect(created.manifest.runtime_session_ids).toEqual([]);
  await expect(page.getByRole('heading',{name:'Architecture facts',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Inspect evidence',exact:true}).first().click();
  await expect(page.getByRole('heading',{name:'Supporting evidence',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Discovery',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Guided runtime discovery',exact:true})).toBeVisible();
  await page.getByLabel('Discovery update note',{exact:true}).fill('Schedule an owner workflow for the next runtime capture.');
  await page.getByRole('combobox',{name:/Status for/}).first().selectOption('PLANNED');
  await expect(page.getByRole('combobox',{name:/Status for/}).first()).toHaveValue('PLANNED');
  await page.getByRole('button',{name:'Rebuild graph projection',exact:true}).click();
  await expect(page.getByText(/Last projection: APPLIED/)).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'Graph',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Persistent knowledge graph',exact:true})).toBeVisible();
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/phase4-knowledge-graph.png',fullPage:true});
  await page.getByRole('button',{name:'Twin',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Architecture digital twin',exact:true})).toBeVisible();
  await expect(page.getByText('Data ownership is not established by database calls.',{exact:true})).toBeVisible();
  const exported=await page.request.get('/api/v1/architecture-versions/'+created.id+'/export');expect(exported.ok()).toBeTruthy();
  expect((await exported.json()).facts.length).toBeGreaterThan(0);
  await page.reload();await page.getByRole('button',{name:'Evidence & digital twin',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Architecture version',exact:true})).toHaveValue(created.id);
  expect(errors).toEqual([]);
});
