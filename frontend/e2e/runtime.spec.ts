import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('real PetClinic runtime evidence is inspectable through the UI',async({page})=>{
  const reportPath=path.resolve('../docs/runtime-validation.json');
  test.skip(!fs.existsSync(reportPath),'Run real PetClinic validation first.');
  const report=JSON.parse(fs.readFileSync(reportPath,'utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Dynamic analysis',exact:true}).click();
  await page.getByLabel('Runtime application').selectOption(report.application_id);
  await page.getByRole('row').filter({hasText:report.session_id.slice(0,8)}).getByRole('checkbox').check();
  await expect(page.getByRole('heading',{name:'Observation gaps'})).toBeVisible();
  await page.screenshot({path:'../docs/screenshots/runtime-coverage.png',fullPage:true});
  await page.getByRole('button',{name:'Graph',exact:true}).click();
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.getByLabel('Runtime graph level').selectOption('classes');
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.getByLabel('Runtime graph mode').selectOption('runtime');
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.getByLabel('Runtime graph mode').selectOption('static');
  await expect(page.locator('.runtime-canvas canvas').first()).toBeVisible();
  await page.getByLabel('Runtime graph mode').selectOption('unified');
  await page.screenshot({path:'../docs/screenshots/runtime-graph.png',fullPage:true});
  await page.getByRole('button',{name:'Mapping',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Static ↔ runtime identities'})).toBeVisible();
  await expect(page.getByRole('cell',{name:'EXACT',exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Flows',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Observed request groups'})).toBeVisible();
  await page.getByRole('button',{name:'Database',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Observed persistence signals'})).toBeVisible();
  await page.getByRole('button',{name:'Modernization',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Structural and runtime readiness'})).toBeVisible();
  await page.getByRole('button',{name:'Assistant',exact:true}).click();
  await page.getByRole('button',{name:'Ask runtime assistant'}).click();
  await expect(page.getByRole('link',{name:'Evidence',exact:true}).first()).toBeVisible();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export evidence',exact:true}).click();
  expect((await download).suggestedFilename()).toBe('archintel-runtime-report.json');
  expect(errors).toEqual([]);
});
