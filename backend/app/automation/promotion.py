"""Promotion of a converted service from the local trial to production, as a reviewed hand-off package.

ArchIntel never deploys and never holds production credentials. A human records a promotion decision; only then can the
deployment package be downloaded: the generated source, the runner's build recipe, Kubernetes and Compose manifests with
placeholders, and a checklist that the user's own CI/CD and reviewers complete.
"""
import io
import json
import zipfile
from pathlib import Path

from fastapi import HTTPException

from app.models import now
from app.config import ROOT

DOCKERFILE_PATH = ROOT / 'runner' / 'recipe' / 'Dockerfile'

DECISIONS = ('APPROVED_FOR_HANDOFF', 'REJECTED')


def decide(job, identity: dict, decision: str, note: str, differences_reviewed: bool) -> dict:
    document = job.document
    if job.kind != 'CONVERT' or job.state != 'COMPLETED' or not document.get('generation'):
        raise HTTPException(409, 'Only a completed conversion with a generated service can be promoted.')
    if decision not in DECISIONS:
        raise HTTPException(422, 'Use APPROVED_FOR_HANDOFF or REJECTED.')
    if not note.strip():
        raise HTTPException(422, 'Explain the decision in a note.')
    if identity.get('kind') != 'HUMAN':
        raise HTTPException(403, 'A human records promotion decisions.')
    verdict = document.get('verdict')
    if decision == 'APPROVED_FOR_HANDOFF' and verdict != 'EQUIVALENT' and not differences_reviewed:
        raise HTTPException(409, f'The trial verdict is {verdict}; confirm that you reviewed every difference before approving.')
    entry = dict(decision=decision, note=note.strip()[:2000], actor_id=identity['id'], at=now().isoformat(), verdict=verdict,
                 differences_reviewed=bool(differences_reviewed), generation_fingerprint=document['generation']['fingerprint'])
    history = list((document.get('promotion') or {}).get('history', [])) + [entry]
    return dict(state=decision, history=history)


def manifests(name: str) -> dict[str, str]:
    image = f'REGISTRY/{name}:TAG'
    k8s = f"""# Placeholders in CAPITALS are filled by your pipeline. ArchIntel does not know your cluster, registry or secrets.
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  labels: {{app: {name}, archintel.trial: converted}}
spec:
  replicas: 2
  selector: {{matchLabels: {{app: {name}}}}}
  template:
    metadata: {{labels: {{app: {name}}}}}
    spec:
      securityContext: {{runAsNonRoot: true, runAsUser: 10001}}
      containers:
        - name: {name}
          image: {image}
          ports: [{{containerPort: 8080}}]
          resources: {{requests: {{cpu: 250m, memory: 512Mi}}, limits: {{cpu: "1", memory: 768Mi}}}}
          readinessProbe: {{httpGet: {{path: /, port: 8080}}, initialDelaySeconds: 20, periodSeconds: 10}}
          livenessProbe: {{httpGet: {{path: /, port: 8080}}, initialDelaySeconds: 60, periodSeconds: 20}}
          securityContext: {{allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {{drop: [ALL]}}}}
          volumeMounts: [{{name: tmp, mountPath: /tmp}}]
          envFrom: [{{secretRef: {{name: {name}-config, optional: true}}}}]
      volumes: [{{name: tmp, emptyDir: {{}}}}]
---
apiVersion: v1
kind: Service
metadata: {{name: {name}}}
spec:
  selector: {{app: {name}}}
  ports: [{{port: 80, targetPort: 8080}}]
"""
    compose = f"""# Local or staging run of the converted service next to the original application.
services:
  {name}:
    build: ..
    image: {image}
    ports: ["127.0.0.1:18200:8080"]
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
"""
    return {'deploy/kubernetes.yaml': k8s, 'deploy/compose.yaml': compose}


def checklist(job) -> str:
    d = job.document
    c = d.get('comparison') or {}
    counts = c.get('counts', {})
    approval = (d.get('promotion') or {}).get('history', [])[-1]
    questions = d['generation'].get('unresolved_questions', [])
    lines = [
        f"# Promotion checklist: {d['candidate_name']}",
        '',
        f"Generated by ArchIntel conversion {job.id} with {d['generation']['usage'].get('model')} from source commit {d['source']['commit'][:12]}.",
        f"Trial verdict: {d.get('verdict')} ({counts.get('EQUIVALENT', 0)} of {c.get('total', 0)} replayed scenarios equivalent).",
        f"Hand-off approved by {approval['actor_id']} at {approval['at']}: {approval['note']}",
        '',
        '## Before production of this application change (complete in your own pipeline)',
        '- [ ] Code review of every generated file of the selected candidate by the owning team.',
        '- [ ] The build passes in your CI with your dependency and vulnerability scanning.',
        '- [ ] Every open question below has an owner and an answer before this plan continues.',
        '- [ ] Data ownership decided for this application: which tables the service owns, and the migration from the shared database.',
        '- [ ] Configuration and secrets come from your secret manager; the artifact contains none.',
        '- [ ] Routing: the gateway or this application sends the selected candidate\'s routes to the service (strangler step), with a rollback switch.',
        '- [ ] Behaviour checked again in staging with the selected recorded scenarios and your own tests.',
        '- [ ] Observability: logs, metrics and traces of this application reach your platform; alerts are defined.',
        '- [ ] Rollback plan tested: routes return to this application without data loss.',
        '',
        '## Open questions from generation',
        *([f'- {q}' for q in questions] or ['- None recorded.']),
        '',
        '## Limits of the trial',
        *[f'- {item}' for item in d.get('limitations', [])],
    ]
    return '\n'.join(lines) + '\n'


def package(job, data_dir) -> bytes:
    d = job.document
    if (d.get('promotion') or {}).get('state') != 'APPROVED_FOR_HANDOFF':
        raise HTTPException(409, 'Record a promotion approval before downloading the deployment package.')
    root = Path(data_dir) / 'conversions' / job.id / d['service_name']
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as archive:
        for entry in d['generation']['files']:
            path = (root / entry['path']).resolve()
            if not path.is_relative_to(root.resolve()):
                raise HTTPException(409, 'Generated file path left the service folder.')
            archive.writestr(f"{d['service_name']}/{entry['path']}", path.read_text(encoding='utf-8'))
        archive.writestr(f"{d['service_name']}/Dockerfile", DOCKERFILE_PATH.read_text(encoding='utf-8'))
        for path, content in manifests(d['service_name']).items():
            archive.writestr(f"{d['service_name']}/{path}", content)
        archive.writestr(f"{d['service_name']}/PROMOTION.md", checklist(job))
        archive.writestr(f"{d['service_name']}/archintel-conversion.json", json.dumps(dict(
            conversion_id=job.id, candidate=d['candidate_name'], verdict=d.get('verdict'), comparison=d.get('comparison', {}).get('counts'),
            generation_fingerprint=d['generation']['fingerprint'], source_commit=d['source']['commit'], promotion=d['promotion']), indent=2))
    return buffer.getvalue()
