@dataclass
class DomainDiscoveryConfig:
    """Knobs for candidate-domain discovery. All have safe defaults."""

    # --- 1. scoping -----------------------------------------------------
    excluded_prefixes: tuple[str, ...] = (
        'org.springframework.boot.loader.',
        'org.springframework.boot.autoconfigure.',
        'org.springframework.boot.devtools.',
        'org.apache.',
        'org.hibernate.',
        'jakarta.',
        'javax.',
        'java.',
        'kotlin.',
    )
    extra_excluded_prefixes: tuple[str, ...] = ()
    excluded_name_suffixes: tuple[str, ...] = ('Test', 'Tests', 'Generated', 'AutoGenerated')
    excluded_package_segments: tuple[str, ...] = ('test', 'tests', 'generated')
    spring_boot_application_annotations: tuple[str, ...] = (
        'org.springframework.boot.autoconfigure.SpringBootApplication',
        'org.springframework.boot.SpringBootConfiguration',
    )

    # --- 2. affinity weights -------------------------------------------
    max_trace_classes: int = 500
    shared_data_weight: float = 1.0
    package_prior: float = 0.3
    parent_package_prior: float = 0.1

    # --- 3. clustering --------------------------------------------------
    resolutions: tuple[float, ...] = (0.5, 0.8, 1.0, 1.3, 1.8)
    seeds: int = 20
    large_graph_classes: int = 2500
    large_graph_resolutions: tuple[float, ...] = (0.8, 1.0, 1.3)
    large_graph_seeds: int = 8
    consensus_resolution: float = 1.0
    consensus_threshold: float = 0.5
    average_linkage_max_classes: int = 800

    # --- 4. post-processing --------------------------------------------
    min_domain_size: int = 3
    shared_kernel_enabled: bool = True
    shared_kernel_min_communities: int = 3
    hub_percentile: float = 95.0


@dataclass
class ScopedResult:
    classes: dict  # outer fqn -> merged class info (in scope only)
    graph: nx.DiGraph  # folded graph over outer fqns, summed weights, no self loops
    outer_of: dict  # every in-scope original fqn -> outer fqn
    excluded: set
    app_root: str
    excluded_count: int


@dataclass
class ClusterResult:
    partition: dict  # class -> community id (int)
    communities: list  # [sorted class lists], ordered by community id
    stability: dict  # community id -> mean pairwise co-association
    hierarchy: list  # [{resolution, seed, communities, count}] coarse-to-fine
    representative_resolution: float
    fallback: bool
    resolutions_used: list
    seeds_used: list


# --------------------------------------------------------------------------- stage 1


def _match_excluded(fqn: str, cls: dict, config: DomainDiscoveryConfig) -> bool:
    prefixes = config.excluded_prefixes + config.extra_excluded_prefixes
    if any(fqn.startswith(p) for p in prefixes):
        return True
    simple = cls.get('simple_name') or fqn.rsplit('.', 1)[-1]
    if any(simple.endswith(s) for s in config.excluded_name_suffixes):
        return True
    package = cls.get('package_name') or fqn.rpartition('.')[0]
    segments = package.split('.') if package else []
    return any(seg in config.excluded_package_segments for seg in segments)


def _longest_common_package_prefix(packages) -> str:
    packages = sorted({p for p in packages if p})
    if not packages:
        return ''
    parts = [p.split('.') for p in packages]
    common = 0
    while all(len(p) > common for p in parts) and len({p[common] for p in parts}) == 1:
        common += 1
    return '.'.join(parts[0][:common])


def scope_classes(classes: dict, graph: nx.DiGraph,
                  config: DomainDiscoveryConfig | None = None) -> ScopedResult:
    """Exclude framework classes, find the application root, fold inner classes.

    Excluded classes are *not* dropped: they surface through the reserved
    membership id 'excluded-framework' (see discover_domains).
    """
    config = config or DomainDiscoveryConfig()
    excluded: set = set()
    in_scope: dict = {}
    for fqn in sorted(classes):
        cls = classes[fqn]
        if _match_excluded(fqn, cls, config):
            excluded.add(fqn)
        else:
            in_scope[fqn] = dict(cls)

    app_root = ''
    for fqn in sorted(in_scope):
        annotations = in_scope[fqn].get('annotations', [])
        if any(a in config.spring_boot_application_annotations for a in annotations):
            app_root = in_scope[fqn].get('package_name') or fqn.rpartition('.')[0]
            break
    if not app_root:
        app_root = _longest_common_package_prefix(
            c.get('package_name') or fqn.rpartition('.')[0] for fqn, c in in_scope.items())

    # Fold inner classes (com.example.Outer$Inner -> com.example.Outer) onto
    # their outer class; edges and annotations aggregate onto the outer.
    outer_of: dict = {}
    for fqn in sorted(in_scope):
        outer = fqn.split('$')[0]
        outer_of[fqn] = outer if outer in in_scope else fqn

    merged: dict = {}
    for fqn in sorted(in_scope):
        outer = outer_of[fqn]
        if outer == fqn:
            merged.setdefault(fqn, dict(in_scope[fqn]))
        else:
            base = merged.setdefault(outer, dict(in_scope[outer]))
            base_ann = set(base.get('annotations', []))
            base_ann.update(in_scope[fqn].get('annotations', []))
            base['annotations'] = sorted(base_ann)

    folded = nx.DiGraph()
    for outer in merged:
        folded.add_node(outer, **merged[outer])
    for u in sorted(in_scope):
        ou = outer_of[u]
        for v in sorted(graph.successors(u)):
            if v not in in_scope:
                continue
            ov = outer_of[v]
            if ou == ov:  # drop self-loops introduced by folding
                continue
            weight = graph[u][v].get('weight', 1)
            if folded.has_edge(ou, ov):
                folded[ou][ov]['weight'] += weight
            else:
                folded.add_edge(ou, ov, weight=weight)

    return ScopedResult(
        classes=merged, graph=folded, outer_of=outer_of, excluded=excluded,
        app_root=app_root, excluded_count=len(excluded),
    )


# --------------------------------------------------------------------------- stage 2


def _trace_members(trace, classes: dict) -> list:
    """Unique in-scope classes referenced by one runtime trace (inner classes
    resolve to their outer class). Sorted for determinism."""
    found = []
    for c in trace:
        if c in classes:
            found.append(c)
        else:
            outer = c.split('$')[0] if '$' in c else c
            if outer in classes:
                found.append(outer)
    return sorted(set(found))


def _derive_entity_groups(classes: dict, graph: nx.DiGraph) -> list:
    """Derive shared-data groups from @Entity/@Repository annotations plus
    repository -> entity successor edges (default when entity_groups is None)."""
    entities = set()
    repositories = set()
    for n in sorted(classes):
        annotations = classes[n].get('annotations', [])
        if any(a.endswith('.Entity') for a in annotations):
            entities.add(n)
        if any(a.endswith('.Repository') for a in annotations):
            repositories.add(n)
    groups: dict = {e: {e} for e in entities}
    for r in sorted(repositories):
        for succ in sorted(graph.successors(r)):
            if succ in entities:
                groups.setdefault(succ, set()).add(r)
    return [g for g in groups.values() if len(g) >= 2]


def build_affinity_graph(classes: dict, graph: nx.DiGraph, traces=None,
                         entity_groups=None, config: DomainDiscoveryConfig | None = None) -> nx.Graph:
    """Undirected weighted affinity graph over in-scope classes.

    Fixes the old overwrite bug: A->B and B->A weights SUM on the undirected edge.
    """
    config = config or DomainDiscoveryConfig()
    nodes = sorted(classes)
    affinity: dict = defaultdict(float)
    in_degree = {n: graph.in_degree(n) for n in nodes}

    # Static edges: weight / log2(2 + in_degree(target)) (hub damping),
    # both directions summed.
    for u in nodes:
        for v in sorted(graph.successors(u)):
            if v not in classes:
                continue
            w = graph[u][v].get('weight', 1) / math.log2(2 + in_degree[v])
            key = (u, v) if u <= v else (v, u)
            affinity[key] += w

    # Runtime co-occurrence: 0.5 / len(trace_classes) per pair in the same trace.
    if traces:
        for trace in traces:
            members = _trace_members(trace, classes)
            count = len(members)
            if count == 0 or count > config.max_trace_classes:
                continue
            share = 0.5 / count
            for a, b in itertools.combinations(members, 2):
                affinity[(a, b)] += share

    # Shared data: +shared_data_weight per pair touching the same entity/repository.
    groups = [set(g) for g in entity_groups] if entity_groups else _derive_entity_groups(classes, graph)
    in_scope = set(nodes)
    for group in groups:
        members = sorted(group & in_scope)
        if len(members) < 2:
            continue
        for a, b in itertools.combinations(members, 2):
            affinity[(a, b)] += config.shared_data_weight

    # Weak package proximity priors (never a grouping key).
    by_package: dict = defaultdict(list)
    for n in nodes:
        by_package[classes[n].get('package_name') or ''].append(n)
    for members in by_package.values():
        members.sort()
        for a, b in itertools.combinations(members, 2):
            affinity[(a, b)] += config.package_prior
    if config.parent_package_prior:
        by_parent: dict = defaultdict(list)
        for n in nodes:
            pkg = classes[n].get('package_name') or ''
            by_parent[pkg.rpartition('.')[0]].append(n)
        for members in by_parent.values():
            members.sort()
            for a, b in itertools.combinations(members, 2):
                pa = classes[a].get('package_name') or ''
                pb = classes[b].get('package_name') or ''
                if pa != pb and pa.rpartition('.')[0] == pb.rpartition('.')[0]:
                    affinity[(a, b)] += config.parent_package_prior

    g = nx.Graph()
    g.add_nodes_from(nodes)
    for (a, b), w in affinity.items():
        if w > 0:
            g.add_edge(a, b, weight=w)
    return g


# --------------------------------------------------------------------------- stage 3


def _percentile(values: list, p: float) -> float:
    if not values:
        return 0.0
    values = sorted(values)
    if not 0 <= p <= 100:
        raise ValueError('percentile must be in [0, 100]')
    if len(values) == 1:
        return float(values[0])
    rank = (p / 100.0) * (len(values) - 1)
    lo = int(math.floor(rank))
    hi = int(math.ceil(rank))
    if lo == hi:
        return float(values[lo])
    return values[lo] + (values[hi] - values[lo]) * (rank - lo)


def _igraph_from_affinity(affinity: nx.Graph, names: list):
    index = {n: i for i, n in enumerate(names)}
    edges = [(index[a], index[b]) for a, b in affinity.edges]
    g = _ig.Graph(n=len(names), edges=edges, directed=False)
    g.vs['name'] = names
    if edges:
        g.es['weight'] = [float(affinity[a][b]['weight']) for a, b in affinity.edges]
    return g


def _leiden_run(g, names: list, resolution: float, seed: int):
    weights = [float(e['weight']) for e in g.es] or None
    partition = _leidenalg.find_partition(
        g, _leidenalg.RBConfigurationVertexPartition,
        weights=weights, resolution_parameter=resolution, seed=seed,
    )
    membership = list(partition.membership)
    comms: dict = defaultdict(list)
    for i, cid in enumerate(membership):
        comms[cid].append(names[i])
    communities = [sorted(members) for members in sorted(comms.values(), key=lambda m: m[0])]
    id_of = {n: i for i, members in enumerate(communities) for n in members}
    return id_of, communities


def _renumber_partition(raw: dict, names: list):
    """Renumber an arbitrary community-id mapping deterministically: communities
    ordered by their smallest member, ids 0..k-1."""
    comms: dict = defaultdict(list)
    for n in names:
        comms[raw[n]].append(n)
    communities = [sorted(members) for members in sorted(comms.values(), key=lambda m: m[0])]
    id_of = {n: i for i, members in enumerate(communities) for n in members}
    return id_of, communities


def _average_linkage(coassoc: dict, names: list, threshold: float):
    """Agglomerative average-linkage clustering on a co-association matrix.

    Repeatedly merges the pair of clusters with the highest mean pairwise
    co-association while it is at or above ``threshold``. Deterministic:
    ties are broken by the smallest member of each cluster.
    """
    clusters = [frozenset({n}) for n in names]
    while len(clusters) > 1:
        best_avg = -1.0
        best_i = best_j = -1
        best_key = None
        for i in range(len(clusters)):
            ci = clusters[i]
            for j in range(i + 1, len(clusters)):
                cj = clusters[j]
                total = 0.0
                count = 0
                for a in ci:
                    for b in cj:
                        total += coassoc.get((a, b) if a <= b else (b, a), 0.0)
                        count += 1
                avg = total / count
                key = (min(ci), min(cj))
                if avg > best_avg or (avg == best_avg and key < best_key):
                    best_avg = avg
                    best_i, best_j = i, j
                    best_key = key
        if best_avg < threshold:
            break
        clusters[best_i] = clusters[best_i] | clusters[best_j]
        del clusters[best_j]
    communities = [sorted(c) for c in sorted(clusters, key=lambda c: min(c))]
    partition = {n: i for i, members in enumerate(communities) for n in members}
    return partition, communities


def cluster_consensus(affinity: nx.Graph,
                      config: DomainDiscoveryConfig | None = None) -> ClusterResult:
    """Leiden consensus over resolutions x seeds; Louvain fallback if unavailable."""
    config = config or DomainDiscoveryConfig()
    names = sorted(affinity.nodes)
    if not names:
        return ClusterResult({}, [], {}, [], 0.0, False, [], [])

    resolutions = list(config.resolutions)
    seeds = list(range(config.seeds))
    if len(names) > config.large_graph_classes:
        resolutions = list(config.large_graph_resolutions)
        seeds = list(range(config.large_graph_seeds))

    fallback = not _LEIDEN_AVAILABLE
    runs: list = []  # (resolution, seed, communities)
    hierarchy: list = []
    if _LEIDEN_AVAILABLE:
        g = _igraph_from_affinity(affinity, names)
        for res in resolutions:
            for seed in seeds:
                _, communities = _leiden_run(g, names, res, seed)
                runs.append((res, seed, communities))
            if seeds:
                _, comm0 = _leiden_run(g, names, res, seeds[0])
                hierarchy.append(dict(resolution=res, seed=seeds[0],
                                      communities=comm0, count=len(comm0)))
    else:
        raw = community_louvain.best_partition(affinity, random_state=42, weight='weight') \
            if affinity.number_of_edges() else {n: i for i, n in enumerate(names)}
        partition, communities = _renumber_partition(raw, names)
        return ClusterResult(partition, communities, {i: 1.0 for i in range(len(communities))},
                             [], 0.0, True, resolutions, seeds)

    # Co-association matrix: fraction of runs sharing a community.
    index = {n: i for i, n in enumerate(names)}
    total = max(len(runs), 1)
    nn = len(names)
    counts_mat = None
    counts_dict = None
    if _HAS_NUMPY:
        counts_mat = np.zeros((nn, nn), dtype=np.int32)
        for _, _, comms in runs:
            labels = np.zeros(nn, dtype=np.int32)
            for cid, members in enumerate(comms):
                for m in members:
                    labels[index[m]] = cid
            counts_mat += (labels[:, None] == labels[None, :])
    else:
        counts_dict = defaultdict(int)
        for _, _, comms in runs:
            for members in comms:
                for a, b in itertools.combinations(members, 2):
                    i, j = index[a], index[b]
                    counts_dict[(i, j) if i < j else (j, i)] += 1

    def coassoc_get(a: str, b: str) -> float:
        i, j = index[a], index[b]
        if counts_mat is not None:
            return float(counts_mat[i, j]) / total
        return counts_dict.get((i, j) if i < j else (j, i), 0) / total

    def coassoc_items():
        """Yield (a, b, frac) for every pair with nonzero co-association."""
        if counts_mat is not None:
            ii, jj = np.nonzero(np.triu(counts_mat, k=1))
            for i, j in zip(ii.tolist(), jj.tolist()):
                w = counts_mat[i, j] / total
                if w > 0:
                    yield names[i], names[j], float(w)
        else:
            for (i, j), cnt in counts_dict.items():
                w = cnt / total
                if w > 0:
                    yield names[i], names[j], w

    # Representative resolution: closest to the median community count.
    counts_by_res = defaultdict(list)
    for res, seed, comms in runs:
        counts_by_res[res].append(len(comms))
    median_count = _percentile([sum(v) / len(v) for v in counts_by_res.values()], 50) \
        if counts_by_res else 0
    representative = min(resolutions,
                         key=lambda r: (abs((sum(counts_by_res[r]) / len(counts_by_res[r])) - median_count), r))

    # Final partition. Small graphs use average-linkage consensus on the
    # co-association matrix; large graphs reuse the partition at the
    # representative resolution (computed during the sweep) to avoid
    # building a dense co-association graph.
    if len(names) <= config.average_linkage_max_classes:
        coassoc_dict_named = {}
        for a, b, w in coassoc_items():
            coassoc_dict_named[(a, b) if a <= b else (b, a)] = w
        if coassoc_dict_named:
            partition, communities = _average_linkage(coassoc_dict_named, names,
                                                      config.consensus_threshold)
        else:
            partition, communities = {n: i for i, n in enumerate(names)}, \
                [[n] for n in names]
    else:
        rep_communities = None
        for entry in hierarchy:
            if entry['resolution'] == representative:
                rep_communities = entry['communities']
                break
        if rep_communities is None:
            rep_communities = hierarchy[-1]['communities'] if hierarchy else [[n] for n in names]
        partition = {n: i for i, members in enumerate(rep_communities) for n in members}
        communities = rep_communities

    # Stability per community: mean pairwise co-association inside it.
    stability = {}
    for cid, members in enumerate(communities):
        if len(members) < 2:
            stability[cid] = 1.0
        else:
            vals = [coassoc_get(a, b) for a, b in itertools.combinations(members, 2)]
            stability[cid] = sum(vals) / len(vals)

    return ClusterResult(
        partition=partition, communities=communities, stability=stability,
        hierarchy=hierarchy, representative_resolution=representative,
        fallback=fallback, resolutions_used=resolutions, seeds_used=seeds,
    )


