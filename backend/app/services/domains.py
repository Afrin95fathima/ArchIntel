def _camel_tokens(name: str) -> list:
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1 \2', name)
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1 \2', s)
    s = s.lower()
    return [t for t in re.split(r'[^a-z0-9]+', s) if len(t) >= 2]


def _community_tokens(members: list, classes: dict) -> Counter:
    tokens = Counter()
    for n in members:
        cls = classes.get(n, {})
        simple = cls.get('simple_name') or n.rsplit('.', 1)[-1]
        tokens.update(_camel_tokens(simple))
        if any(a.endswith('.Entity') for a in cls.get('annotations', [])):
            tokens.update(_camel_tokens(simple))  # entity name carries domain semantics
        package = cls.get('package_name') or n.rpartition('.')[0]
        for seg in package.split('.'):
            if seg and seg.lower() not in GENERIC:
                tokens[seg.lower()] += 1
    return tokens


def name_domains(communities: dict, shared_kernel: set, member_cid: dict,
                 classes: dict, affinity: nx.Graph, app_root: str, config: DomainDiscoveryConfig,
                 excluded_count: int, signals: list, cluster: ClusterResult):
    """Build domain dicts. Names come from TF-IDF evidence, not the package alone."""
    config = config or DomainDiscoveryConfig()
    ordered = []
    for cid, members in communities.items():
        ordered.append((cid, sorted(members)))
    ordered.sort(key=lambda item: (-len(item[1]), min(item[1])))
    if shared_kernel:
        ordered.append((-1, sorted(shared_kernel)))

    # TF-IDF over identifier tokens.
    token_counts = {cid: _community_tokens(members, classes) for cid, members in ordered}
    n_communities = len(ordered)
    token_dfs: dict = defaultdict(int)
    for cid, _ in ordered:
        for token in token_counts[cid]:
            token_dfs[token] += 1
    ranked: dict = {}
    for cid, _ in ordered:
        total = sum(token_counts[cid].values()) or 1
        scored = []
        for token, count in token_counts[cid].items():
            df = token_dfs[token]
            scored.append((token, (count / total) * math.log(n_communities / df)))
        scored.sort(key=lambda item: (-item[1], item[0]))
        ranked[cid] = scored

    def build_name(cid: int) -> tuple[str, list]:
        best = ranked[cid]
        tokens = [best[0][0]] if best else []
        if len(best) > 1 and best[1][1] > 0.4 * best[0][1] and best[1][0] not in tokens:
            tokens.append(best[1][0])
        return ' '.join(t.title() for t in tokens), best

    used_names: set = set()
    domains: list = []
    cid_to_domain_id: dict = {}
    for cid, members in ordered:
        is_kernel = cid == -1
        name, best = build_name(cid)
        original = name
        suffix_index = 0
        while name in used_names:
            suffix_index += 1
            extra = next((t for t, _ in best[suffix_index:] if t not in name.split()), None)
            name = f"{original} {extra.title()}" if extra else f"{original} {suffix_index}"
        used_names.add(name)

        members = sorted(members)
        member_set = set(members)
        internal = external = 0.0
        for a in members:
            for b in affinity.neighbors(a):
                if b <= a:
                    continue
                if b in member_set:
                    internal += affinity[a][b]['weight']
                else:
                    external += affinity[a][b]['weight']
        total_w = internal + external
        conductance = external / total_w if total_w > 0 else 0.0
        stability = cluster.stability.get(cid, 1.0)
        size_factor = min(1.0, len(members) / 8.0)
        confidence = min(1.0, max(0.0, 0.5 * stability + 0.3 * (1.0 - conductance)
                                + 0.2 * size_factor))
        if is_kernel:
            confidence = min(confidence, 0.5)

        # Highest in-cluster fan-in class as a secondary naming hint.
        fan_in = {n: sum(affinity[m][n]['weight'] for m in members if m != n
                         and affinity.has_edge(m, n)) for n in members}
        fan_in_class = sorted(member_set, key=lambda n: (-fan_in.get(n, 0.0), n))[0] if members else ''

        evidence = [
            f"Stability: {stability:.1%} (mean pairwise co-association over {len(cluster.resolutions_used)} resolutions x {len(cluster.seeds_used)} seeds)",
            f"Conductance: {conductance:.3f} = external / (internal + external) affinity weight",
            f"Resolutions: {', '.join(map(str, cluster.resolutions_used))}; seeds: 0..{len(cluster.seeds_used) - 1}",
            f"Excluded framework/loader/test classes: {excluded_count}",
            f"Signals: {', '.join(signals)}",
            f"Fan-in hint: {fan_in_class}",
        ]
        if is_kernel:
            evidence.insert(0, 'Shared Kernel: hub classes (top in-degree) connected to multiple communities, plus isolated classes.')

        domains.append(dict(
            id=stable_id('domain', '|'.join(members)),
            name=name,
            domain_source='AUTO',
            confidence=round(confidence, 2),
            class_count=len(members),
            package_count=len({classes[n].get('package_name') or n.rpartition('.')[0] for n in members}),
            classes=members,
            packages=sorted({classes[n].get('package_name') or n.rpartition('.')[0] for n in members}),
            evidence=evidence,
            confidence_note='Boundary confidence = 0.5 × stability + 0.3 × (1 - conductance) + 0.2 × size factor; it is a heuristic, not a calibrated probability.',
        ))
        cid_to_domain_id[cid] = domains[-1]['id']

    domains.sort(key=lambda d: d['id'])
    return domains, cid_to_domain_id


