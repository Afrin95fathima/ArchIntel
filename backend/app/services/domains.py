"""Deterministic, evidence-bearing candidate domains; not business truth.

Discovery pipeline (each stage is separately testable):

1. scope_classes      - exclude framework/loader/generated/test classes, pick the
                         application root, fold inner classes onto their outer class.
2. build_affinity_graph - undirected weighted graph from static edges (hub damped),
                          runtime trace co-occurrence, shared entity/repository data,
                          and a weak package proximity prior.
3. cluster_consensus  - Leiden over resolutions x seeds with a co-association
                          consensus, falling back to Louvain when unavailable.
4. postprocess        - min-size merging, explicit Shared Kernel for hubs, attach
                         isolated classes to package mates or the Shared Kernel.
5. name_domains       - TF-IDF naming from evidence, confidence from stability /
                        conductance / size.

The public contract is unchanged: discover_domains(classes, graph) -> (domains, membership)
and every domain keeps the keys read by the report/proposal code
(id, name, domain_source, confidence, class_count, package_count, classes, packages,
evidence, confidence_note).
"""
