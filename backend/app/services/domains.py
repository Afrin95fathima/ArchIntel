def discover_domains(classes: dict, graph: nx.DiGraph, traces=None,
                     entity_groups=None, config: DomainDiscoveryConfig | None = None):
    """Candidate domains for the application classes in ``graph``.

    Returns (domains, membership). Every in-scope class is present in
    ``membership``; excluded framework/loader/test classes map to the reserved
    id 'excluded-framework' and are not emitted as candidate domains.
    """
    config = config or DomainDiscoveryConfig()
    if not classes:
        return [], {}

    scoped = scope_classes(classes, graph, config)
    if not scoped.classes:
        membership = {fqn: EXCLUDED_FRAMEWORK_ID for fqn in scoped.excluded}
        return [], membership

    affinity = build_affinity_graph(scoped.classes, scoped.graph, traces,
                                    entity_groups, config)
    cluster = cluster_consensus(affinity, config)
    member_cid, communities, shared_kernel = postprocess(
        cluster.partition, affinity, scoped.graph, config)

    static_signal = scoped.graph.number_of_edges() > 0
    runtime_signal = bool(traces)
    data_signal = bool(entity_groups) or any(
        any(a.endswith(('.Entity', '.Repository')) for a in c.get('annotations', []))
        for c in scoped.classes.values())
    signals = ['package-prior'] + ([s for s, present in (
        ('static', static_signal), ('runtime', runtime_signal), ('data', data_signal))
        if present])

    domains, cid_to_domain_id = name_domains(
        communities, shared_kernel, member_cid, scoped.classes, affinity,
        scoped.app_root, config, scoped.excluded_count, signals, cluster)
    if cluster.fallback:
        for d in domains:
            d['evidence'].insert(0, 'Community detection: Louvain fallback (seed 42); leidenalg/igraph unavailable.')
    else:
        seed_phrase = f"{len(cluster.seeds_used)} seeds (0..{len(cluster.seeds_used) - 1})"
        for d in domains:
            d['evidence'].append(f"Community detection: Leiden consensus ({seed_phrase}).")

    kernel_domain_id = cid_to_domain_id.get(-1)
    membership = {}
    for fqn in scoped.excluded:
        membership[fqn] = EXCLUDED_FRAMEWORK_ID
    for fqn, outer in scoped.outer_of.items():
        if outer in shared_kernel:
            membership[fqn] = kernel_domain_id
        else:
            membership[fqn] = cid_to_domain_id[member_cid[outer]]

    return domains, membership


def _community_graph(graph: nx.DiGraph) -> nx.Graph:
    """Copy only topology and weights; class-node metadata is unused by Louvain."""
    lightweight = nx.Graph()
    lightweight.add_nodes_from(graph.nodes)
    lightweight.add_edges_from((source, target, {'weight': data.get('weight', 1)})
        for source, target, data in graph.edges(data=True))
    return lightweight


def enrich_domains(domains: list[dict], membership: dict, graph: nx.DiGraph, classes: dict, external_edges: list[dict]) -> None:
    db_words = ('java.sql.', 'javax.sql.', 'jakarta.persistence.', 'javax.persistence.', 'JdbcTemplate', 'DataSource', 'JpaRepository', 'CrudRepository')
    for domain in domains:
        members = set(domain['classes'])
        internal = [(s, t) for s, t in graph.edges if s in members and t in members]
        outgoing = [(s, t) for s, t in graph.edges if s in members and t not in members]
        incoming = [(s, t) for s, t in graph.edges if s not in members and t in members]
        db_classes = sorted(n for n in members if any(a.endswith('.Repository') for a in classes[n].get('annotations', [])))
        signals = [e for e in external_edges if e['source'] in members and any(w in e['target'] for w in db_words)]
        repositories = sorted(set(db_classes + [e['source'] for e in signals if 'Repository' in e['target']]))
        entities = sorted(n for n in classes if any(a.endswith('.Entity') for a in classes[n].get('annotations', [])))
        shared = []
        for repo in repositories:
            consumers = sorted({membership[s] for s in graph.predecessors(repo)} | {domain['id']})
            targets = sorted(t for t in graph.successors(repo) if t in entities)
            if len(consumers) > 1:
                shared.append(dict(repository=repo, domains=consumers, entities=targets))
        domain['metrics'] = dict(internal_edges=len(internal), outgoing_edges=len(outgoing), incoming_edges=len(incoming),
            cross_domain_ratio=round(len(outgoing) / (len(internal) + len(outgoing)), 6) if internal or outgoing else 0.0,
            internal_cohesion=round(len(internal) / (len(internal) + len(outgoing)), 6) if internal or outgoing else None,
            internal_density=round(nx.density(graph.subgraph(members)), 6) if len(members) > 1 else 0.0)
        domain_entities = [n for n in entities if n in members]
        repository_entities = [{'repository': repo, 'entities': sorted(t for t in graph.successors(repo) if t in entities)} for repo in repositories]
        domain['database'] = dict(status='STRUCTURAL_SIGNALS' if repositories or signals or domain_entities else 'UNKNOWN',
            repositories=repositories, signals=signals[:50], shared_repositories=shared,
            entities=domain_entities, repository_entities=repository_entities,
            note='Static repository/entity references only. Runtime SQL, transactions and table ownership are unknown.')
