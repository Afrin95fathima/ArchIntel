def postprocess(partition: dict, affinity: nx.Graph, graph: nx.DiGraph,
                config: DomainDiscoveryConfig | None = None):
    """Merge small communities, extract Shared Kernel hubs, attach isolates.

    Returns (member_cid, communities, shared_kernel) where communities excludes
    the Shared Kernel and member_cid covers every in-scope class.
    """
    config = config or DomainDiscoveryConfig()
    member_cid = dict(partition)
    communities: dict = defaultdict(set)
    for n, cid in partition.items():
        communities[cid].add(n)

    shared_kernel: set = set()
    if config.shared_kernel_enabled and communities:
        degrees = {n: graph.in_degree(n) for n in partition}
        p95 = _percentile(sorted(degrees.values()), config.hub_percentile)
        for n in sorted(partition):
            if degrees[n] > p95:
                linked = {member_cid[m] for m in affinity.neighbors(n)}
                if len(linked) >= config.shared_kernel_min_communities:
                    shared_kernel.add(n)
    for h in sorted(shared_kernel):
        communities[member_cid[h]].discard(h)
    communities = {cid: members for cid, members in communities.items() if members}

    def merge_into(source: int, target: int) -> None:
        communities[target] |= communities[source]
        for m in communities[source]:
            member_cid[m] = target
        del communities[source]

    # Merge communities smaller than min_domain_size, smallest first,
    # ties broken by community id, into the most strongly connected neighbor.
    while True:
        small = [cid for cid in communities if len(communities[cid]) < config.min_domain_size]
        if not small:
            break
        source = min(small, key=lambda c: (len(communities[c]), c))
        targets: dict = defaultdict(float)
        for m in communities[source]:
            for nb in affinity.neighbors(m):
                if nb in communities[source]:
                    continue
                targets[member_cid[nb]] += affinity[m][nb]['weight']
        if not targets:
            break  # nothing to merge into; leave as its own community
        target = min(targets, key=lambda c: (-targets[c], c))
        merge_into(source, target)

    # Isolated classes attach to nearest package-mates' community, else Shared Kernel.
    isolated = sorted(n for n in member_cid if affinity.degree(n) == 0)
    by_package_all: dict = defaultdict(list)
    for n in member_cid:
        by_package_all[n.rpartition('.')[0]].append(n)
    for n in isolated:
        package_mates = [m for m in by_package_all[n.rpartition('.')[0]] if m != n]
        chosen = None
        if package_mates:
            counts: dict = defaultdict(int)
            for m in package_mates:
                counts[member_cid[m]] += 1
            chosen = min(counts, key=lambda c: (-counts[c], c))
        if chosen is not None:
            communities.setdefault(chosen, set()).add(n)
            member_cid[n] = chosen
        elif config.shared_kernel_enabled:
            shared_kernel.add(n)
            member_cid[n] = n  # unique temporary marker, resolved below
        # else: left as a singleton community

    # Final community ids: shared kernel members leave their communities.
    communities = {cid: {m for m in members if m not in shared_kernel}
                   for cid, members in communities.items()
                   if {m for m in members if m not in shared_kernel}}

    # Renumber communities deterministically (smallest member first).
    # Shared-kernel members are deliberately not part of any community;
    # name_domains emits them as a single explicit "Shared Kernel" domain.
    renumbered: dict = {}
    comms: dict = defaultdict(set)
    for n in sorted({m for members in communities.values() for m in members}):
        comms[member_cid[n]].add(n)
    new_id = 0
    for old_cid in sorted(comms, key=lambda c: min(comms[c])):
        for m in sorted(comms[old_cid]):
            member_cid[m] = new_id
        renumbered[new_id] = set(comms[old_cid])
        new_id += 1

    return member_cid, renumbered, shared_kernel


